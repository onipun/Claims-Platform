// Generates TS types from the backend OpenAPI contracts (../contracts/openapi).
//   npm run gen:api          rewrite src/app/core/api/generated/*.ts
//   npm run gen:api:check    fail (exit 1) if the committed files differ from the contracts
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contracts = resolve(root, '../contracts/openapi');
const out = resolve(root, 'src/app/core/api/generated');
const targets = [
  ['claims-service.json', 'claims.ts'],
  ['insights-service.json', 'insights.ts'],
];
const check = process.argv.includes('--check');
const banner =
  '/* eslint-disable */\n// GENERATED by `npm run gen:api` from contracts/openapi/%S. Do not edit.\n\n';

let drift = false;
mkdirSync(out, { recursive: true });
for (const [spec, file] of targets) {
  const ast = await openapiTS(pathToFileURL(resolve(contracts, spec)));
  const text = banner.replace('%S', spec) + astToString(ast);
  const path = resolve(out, file);
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (current !== text) {
      drift = true;
      console.error(`DRIFT: ${file} does not match contracts/openapi/${spec}. Run "npm run gen:api".`);
    } else console.log(`ok: ${file}`);
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${file}`);
  }
}
process.exit(drift ? 1 : 0);
